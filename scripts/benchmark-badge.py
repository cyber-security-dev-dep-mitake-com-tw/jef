#!/usr/bin/env python3
"""Generate README badges from the benchmark results.

Shields.io endpoint JSON rather than a hardcoded badge URL, so the README cannot
show a number the results file no longer supports. The badge is regenerated by
the nightly run alongside the numbers it reports.

    python scripts/benchmark-badge.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]


#: Green only when the model is beating chance by a wide margin and coverage
#: holds. A badge that is always green tells the reader nothing.
def _colour(value: float, good: float, fair: float) -> str:
    if value >= good:
        return "brightgreen"
    if value >= fair:
        return "yellow"
    return "orange"


def _badge(label: str, message: str, colour: str) -> dict[str, Any]:
    return {"schemaVersion": 1, "label": label, "message": message, "color": colour}


def build(results: dict[str, Any]) -> dict[str, dict[str, Any]]:
    tasks = results.get("tasks", {})
    badges: dict[str, dict[str, Any]] = {}

    vsp = tasks.get("cti-vsp/attack_vector")
    if vsp:
        accuracy = vsp["accuracy"]
        badges["cti-bench-accuracy"] = _badge(
            "CTI-Bench VSP",
            f"{accuracy:.3f} acc (random {vsp['random_baseline']:.2f})",
            _colour(accuracy, 0.75, 0.5),
        )
        coverage = vsp.get("conformal_coverage")
        if coverage is not None:
            badges["conformal-coverage"] = _badge(
                "conformal @0.10",
                f"{coverage:.3f} (nominal 0.90)",
                # Under-covering is the failure this project exists to surface,
                # so it is not allowed to look fine.
                "brightgreen" if coverage >= 0.88 else "red",
            )
        ece = vsp.get("ece_p_correct")
        if ece is not None:
            badges["calibration"] = _badge(
                "P(correct) ECE", f"{ece:.3f}", _colour(1 - ece, 0.93, 0.85)
            )

    tmmlu = [v for k, v in tasks.items() if k.startswith("tmmluplus/")]
    if tmmlu:
        total = sum(v["n"] for v in tmmlu)
        weighted = sum(v["accuracy"] * v["n"] for v in tmmlu) / total
        badges["tmmluplus"] = _badge(
            "TMMLU+",
            f"{weighted:.3f} (chance 0.25 — not a knowledge model)",
            "lightgrey",
        )

    return badges


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate benchmark badges")
    parser.add_argument("--results", default=str(ROOT / "docs" / "benchmarks.json"))
    parser.add_argument("--out", default=str(ROOT / "docs" / "badges"))
    args = parser.parse_args(argv)

    path = Path(args.results)
    if not path.is_file():
        print(f"no results at {path}; run `python -m jef_train.bench` first")
        return 1

    badges = build(json.loads(path.read_text(encoding="utf-8")))
    if not badges:
        print("results carry no task this script knows how to badge")
        return 1

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, payload in badges.items():
        (out / f"{name}.json").write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        print(f"{name:22s} {payload['message']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
